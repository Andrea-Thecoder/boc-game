const CHARS = Object.keys(G).join('');
const PER_ROW = 16;

function build(scene: Phaser.Scene, key: string, ink: string, outline: string | null) {
  const cw = outline ? 7 : 6;
  const ch = outline ? 9 : 8;
  const ox = outline ? 1 : 0;
  const rows = Math.ceil(CHARS.length / PER_ROW);
  const p = new Painter(cw * PER_ROW, ch * rows);
  [...CHARS].forEach((c, idx) => {
    const gx = (idx % PER_ROW) * cw + ox;
    const gy = Math.floor(idx / PER_ROW) * ch + ox;
    G[c].split(' ').forEach((row, j) => {
      [...row].forEach((v, i) => {
        if (v === '#') p.px(gx + i, gy + j, ink);
      });
    });
    if (outline) p.outline(outline, gx - 1, gy - 1, cw, ch);
  });
  scene.textures.addCanvas(key + '_img', p.canvas);
  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: key + '_img',
    width: cw,
    height: ch,
    chars: CHARS,
    charsPerRow: PER_ROW,
    'spacing.x': 0,
    'spacing.y': 0,
    'offset.x': 0,
    'offset.y': 0,
    lineSpacing: outline ? 1 : 2,
  });
  scene.cache.bitmapFont.add(key, data);
}

export function registerFonts(scene: Phaser.Scene) {
  build(scene, 'px', P.white, null);
  build(scene, 'pxo', P.white, P.black);
}
